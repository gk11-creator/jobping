def get_search_keyword(category: str) -> str:
    """
    카테고리 문자열을 받아 검색용 키워드를 반환.
    1) 정확히 일치하면 그대로 매핑값 사용
    2) 부분 일치(포함 관계)로 한 번 더 시도
    3) 그래도 못 찾으면 카테고리 원문을 그대로 검색어로 사용 (최후 수단)
    """
    if not category:
        return ""

    if category in CATEGORY_SEARCH_KEYWORD:
        return CATEGORY_SEARCH_KEYWORD[category]

    for key, keyword in CATEGORY_SEARCH_KEYWORD.items():
        if key in category or category in key:
            return keyword

    return category